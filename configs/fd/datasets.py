"""Datasets, roots and splits for FD's own R&D runs.

Everything here is a fact about *our data on our boxes* -- where a dataset is laid
out, how many frames it has, which episodes are withheld. None of it is a fact about
openpi, which is why it lives in the client tree rather than in `config.py`.

Every root is overridable by environment variable so a box that lays data out
differently needs no code change. The defaults are what the vast.ai boxes use.

FRAME COUNTS are recorded here because step counts are derived from them (see
`configs/_shared/schedule.py`). They are measured, not estimated -- from
`meta/info.json` after each dataset was built. If you rebuild a dataset, update the
count here and the step counts recompute themselves.
"""

